        foreach ($translations as $k => $v) {
            // Replace >text<
            $content = str_replace(">".$k."<", ">{{ __('".$k."') }}<", $content);
            // Replace placeholder="text"
            $content = str_replace('placeholder="'.$k.'"', 'placeholder="{{ __(\''.$k.'\') }}"', $content);
